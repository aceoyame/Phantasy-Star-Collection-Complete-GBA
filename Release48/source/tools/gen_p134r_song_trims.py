#!/usr/bin/env python3
"""R15: generate gba/audio_p134r/src/p134r_song_trim.h (per-song P134R headroom).

Input: JSON from the host pre-limit renderer (tools_host/audio_sim/render_pre.cpp +
chip_audio_pre.cpp, built with -DPS4_P134R_SONG_TRIM=0, 1800 frames per song), i.e.
tools_host/audio_sim/p134r_prelimit_headroom_r15.json with p99.9 of |pre-limit mix|.
trim_q8 = min(256, floor(126*256/p99.9)) so that p99.9 of the trimmed mix is <= 126.
"""
import json, sys
from pathlib import Path
R = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else R/'tools_host/audio_sim/p134r_prelimit_headroom_r15.json'
rows = json.loads(src.read_text())
vals = []
for sid in range(0x81, 0xB5):
    r = rows.get(f'{sid:02X}')
    t = 256 if r is None else max(1, min(256, int(126*256/max(r['p99_9'], 1.0))))
    vals.append(t)
lines = ['/* Generated by tools/gen_p134r_song_trims.py -- do not edit. */',
         '#ifndef P134R_SONG_TRIM_H', '#define P134R_SONG_TRIM_H',
         '/* music $81..$B4, Q8 (256 = unity) */',
         'static const unsigned short p134r_song_trim_q8[52] = {']
for i in range(0, 52, 8):
    lines.append('    ' + ', '.join(f'{v:3d}u' for v in vals[i:i+8]) + ',')
lines += ['};', '#endif', '']
out = R/'gba/audio_p134r/src/p134r_song_trim.h'
out.write_text('\n'.join(lines))
print(f'wrote {out}: min {min(vals)} median {sorted(vals)[26]} max {max(vals)}')
