#!/usr/bin/env python3
"""R16c: source damage-number window glyphs (PSIV Fighter_OpenDamageWindow / loc_255C).

Source (ps4disasm): battle init NemDecomps loc_27D778 to VRAM $BC80 (tile $5E4); loc_255C writes a 5x2-tile
window from the word table loc_25EC (ROM $25EC): left corners $E5E4/$F5E4, right corners $EDE4/$FDE4, blank
pair (words 4,5), damage digit pairs from word 6, heal digit pairs from word 26 ($FFFF4183 set).  Palette
line 3 (battle window palette), Genesis H/V flips, colour 0 transparent.

GBA lowering: each 8x16 source column (top tile + bottom tile) becomes one 6x12 glyph:
  * horizontal: the battle-font fold (columns (0),(1,2),(3),(4),(5,6),(7)), stroke colour wins;
  * vertical: border rows 0/15 kept, then interior rows identical to their predecessor are removed
    (longest run first) -- the source digits use 2-pixel strokes, so this preserves every stroke and gap.
Output: gba/battle_damage_window_data.h  (23 glyphs x 72 B: L, R, blank, digits 0-9, heal digits 0-9)
"""
import sys
from pathlib import Path
R = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(R/'tools'))
from md_compression import nemesis_decompress
rom = Path(sys.argv[1] if len(sys.argv) > 1 else R/'references/roms/ps4built.bin').read_bytes()
assert len(rom) == 0x300000
art = nemesis_decompress(rom[0x27D778:])
W = [int.from_bytes(rom[0x25EC+2*i:0x25EE+2*i], 'big') for i in range(46)]
assert W[:6] == [0xE5E4, 0xF5E4, 0xEDE4, 0xFDE4, 0xF5E5, 0xE5E5], [hex(w) for w in W[:6]]
PRIO = {15: 5, 11: 4, 2: 3, 14: 2, 0: 0}
XF = ((0,), (1, 2), (3,), (4,), (5, 6), (7,))
def raw(word):
    t = (word & 0x7FF) - 0x5E4; assert 0 <= t and (t+1)*32 <= len(art)
    r = art[t*32:t*32+32]
    g = [[(r[y*4+(x >> 1)] & 15) if x & 1 else (r[y*4+(x >> 1)] >> 4) for x in range(8)] for y in range(8)]
    if word & 0x1000: g = g[::-1]
    if word & 0x0800: g = [row[::-1] for row in g]
    return g
def hfold(row):
    out = []
    for xs in XF:
        best = 0
        for x in xs:
            if PRIO.get(row[x], 1) > PRIO.get(best, 1): best = row[x]
        out.append(best)
    return out
def column(top, bot, drop_rows):
    g = [hfold(r) for r in raw(top) + raw(bot)]
    keep = [r for r in range(16) if r not in drop_rows]
    # rows adjacent to the frame lines (1 and 14) are protected; remove interior rows identical to
    # their predecessor (longest run first), then fill-only rows next to the frame.
    def interior(k): return 2 <= keep[k] <= 13
    while len(keep) > 12:
        best = None
        for k in range(1, len(keep)):
            if interior(k) and g[keep[k]] == g[keep[k-1]]:
                run = 1; j = k
                while j + 1 < len(keep) and interior(j+1) and g[keep[j+1]] == g[keep[k]]: run += 1; j += 1
                if best is None or run > best[1]: best = (k, run)
        if best is None:
            fill = [k for k in range(len(keep)) if interior(k) and all(c in (14, 0) for c in g[keep[k]])]
            best = (fill[0] if fill else len(keep)//2, 0)
        keep.pop(best[0])
    return bytes(c for r in keep for c in g[r])
cols = [(W[0], W[1]), (W[2], W[3]), (W[4], W[5])] + [(W[6+2*d], W[7+2*d]) for d in range(10)] + [(W[26+2*d], W[27+2*d]) for d in range(10)]
# rows that are fully transparent in every column are removed globally (keeps the frame aligned)
drop = [r for r in (0, 15) if all(all(c == 0 for c in hfold((raw(t) + raw(b))[r])) for t, b in cols)]
glyphs = [column(t, b, drop) for t, b in cols]
print('globally dropped transparent rows:', drop)
lines = ['/* Generated by tools/gen_battle_damage_window.py from the verified US PSIV ROM -- do not edit. */',
         '#ifndef BATTLE_DAMAGE_WINDOW_DATA_H', '#define BATTLE_DAMAGE_WINDOW_DATA_H',
         '#define BATTLE_DAMAGE_GLYPH_W 6u', '#define BATTLE_DAMAGE_GLYPH_H 12u',
         '#define BATTLE_DAMAGE_GLYPH_LEFT 0u', '#define BATTLE_DAMAGE_GLYPH_RIGHT 1u', '#define BATTLE_DAMAGE_GLYPH_BLANK 2u',
         '#define BATTLE_DAMAGE_GLYPH_DIGIT 3u', '#define BATTLE_DAMAGE_GLYPH_HEAL 13u',
         '/* palette-line-3 nibbles, 0 = transparent */',
         f'static const uint8_t battle_damage_glyphs[{len(glyphs)}u*72u] = {{']
for g in glyphs: lines.append('    ' + ','.join(str(b) for b in g) + ',')
lines += ['};', '#endif', '']
(R/'gba/battle_damage_window_data.h').write_text('\n'.join(lines))
print(f'wrote gba/battle_damage_window_data.h: {len(glyphs)} glyphs x 72 B = {len(glyphs)*72} B (nemesis art {len(art)} B)')
