#!/usr/bin/env python3
"""Pack gbake's bank_raw.bin into the runtime bank.

  mkbank.py bank_raw.bin OUT.c [--tol 6] [--regions ADDR:SIZE,ADDR:SIZE,...]

* Every stage table of every record goes into one pool; a table whose shape (normalised to its peak) is within --tol
  (rms, of 127) of one already in the pool of the same length is not stored again - the per-stage gain is kept in the
  record, so a table that only differs in level costs nothing.  A record names the table of each stage by a 16 bit index
  into snd_tabs[] (cartridge address of the table | log2(length) - 5).
* --sndidx puts the two index arrays into the .sndidx section (the build links it to a fixed ROM address); OUT_idx_size.txt holds
  its size in bytes (the zone array is 36 B per zone, then the directory, 4 B per table).
* OUT.c holds the zone index (sorted by hash, block) and the table directory.  Without --regions the table data is an array
  in OUT.c and snd_data0 points at it (host tests).  With --regions the pool is packed (first fit, largest first) into the
  listed free ROM areas, OUT_<n>.bin holds the data of area n and OUT.json says where each goes; snd_data0 is 0.
"""
import struct, sys, argparse, json
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument('raw'); ap.add_argument('out')
ap.add_argument('--tol', type=float, default=6.0, help='rms difference (of 127) below which stage tables are shared')
ap.add_argument('--regions', default=None)
ap.add_argument('--sndidx', action='store_true', help='put the index arrays in the .sndidx section (placed at an address chosen by the build) and write OUT_idx_size.txt')
a = ap.parse_args()

d = open(a.raw, 'rb').read(); p = 0; recs = []
while p < len(d):
    h, blk, sub, rho, _ = struct.unpack_from('<IBBBB', d, p); gain = list(d[p + 8:p + 16]); nbs = list(d[p + 16:p + 24]); nzg = list(d[p + 24:p + 32]); p += 32
    tabs = []
    for s in range(8):
        N = 1 << nbs[s]
        tabs.append(np.frombuffer(d, dtype=np.int8, count=N, offset=p).astype(np.float64)); p += N
    recs.append((h, blk, sub, rho, gain, nbs, tabs, nzg))
recs.sort(key=lambda r: (r[0], r[1]))

def norm(t):
    m = np.abs(t).max()
    return t / m * 127 if m > 0 else t

pool = {}                   # N -> (list of tables, stacked normalised array)
tabs_out = []               # (N, table) in the order of snd_tabs
tid_of = {}
def intern(t):
    N = len(t); nt = norm(t)
    ent = pool.setdefault(N, [[], np.zeros((0, N)), []])
    if len(ent[0]):
        dist = np.sqrt(np.mean((ent[1] - nt) ** 2, axis=1))
        j = int(np.argmin(dist))
        if dist[j] <= a.tol:
            return ent[2][j]
    tid = len(tabs_out); tabs_out.append((N, t))
    ent[0].append(t); ent[1] = np.vstack([ent[1], nt]); ent[2].append(tid)
    return tid

zones = []
for h, blk, sub, rho, gain, nbs, tabs, nzg in recs:
    tids = []
    for s in range(8):
        tids.append(intern(tabs[s]))
    nz = []                                    # noise supplement level of each stage -> 4 bit (0 = none, else 2^((n+1)/2), 3 dB steps)
    for v in nzg:
        nz.append(0 if v == 0 else int(min(15, max(1, round(2 * np.log2(v) - 1)))))
    zones.append(dict(hash=h, block=blk, sub=sub, rho=rho, gain=gain, tid=tids, nz=nz))

total = sum(n for n, _ in tabs_out)
addr = [0] * len(tabs_out); manifest = []
o = ['/* Generated by mkbank.py from the gbake snapshots.  Do not edit. */', '#include "../mdsnd.h"']
if a.regions:
    regs = []
    for r in a.regions.split(','):
        ad, sz = r.split(':'); regs.append([int(ad, 0), int(sz, 0), bytearray()])
    for i in sorted(range(len(tabs_out)), key=lambda i: -tabs_out[i][0]):
        n, t = tabs_out[i]
        for r in regs:
            if len(r[2]) + n <= r[1]:
                addr[i] = r[0] + len(r[2]); r[2] += bytes(int(v) & 255 for v in t); break
        else:
            sys.exit('bank does not fit: %d bytes of tables, regions hold %d' % (total, sum(r[1] for r in regs)))
    for n, r in enumerate(regs):
        fn = a.out.replace('.c', '_%d.bin' % n); open(fn, 'wb').write(r[2])
        manifest.append(dict(addr=r[0], size=len(r[2]), file=fn))
    json.dump(manifest, open(a.out.replace('.c', '.json'), 'w'), indent=1)
    o.append('const unsigned char *snd_data0 = 0;')
else:
    blob = bytearray()
    for i, (n, t) in enumerate(tabs_out):
        addr[i] = len(blob); blob += bytes(int(v) & 255 for v in t)
    open(a.out.replace('.c', '.bin'), 'wb').write(blob)
    o.append('static const unsigned char snd_bank_data[%d] __attribute__((aligned(4))) = {' % len(blob))
    for i in range(0, len(blob), 24):
        o.append(' ' + ','.join(str(b) for b in blob[i:i + 24]) + ',')
    o.append('};')
    o.append('const unsigned char *snd_data0 = snd_bank_data;')
o.append('const u32 snd_ntabs = %d;' % len(tabs_out))
SEC = ' __attribute__((section(".sndidx")))' if a.sndidx else ''
o.append('const u32 snd_tabs[%d]%s = {' % (len(tabs_out), SEC))
for i, (n, t) in enumerate(tabs_out):
    nb = n.bit_length() - 1; assert nb >= 5 and nb <= 8 and addr[i] % 4 == 0
    o.append(' 0x%08xu,' % (addr[i] | (nb - 5)))
o.append('};')
o.append('const u32 snd_nzones = %d;' % len(zones))
o.append('const snd_zone snd_zones[%d]%s = {' % (len(zones), SEC))
for z in zones:
    nzp = [z['nz'][2 * i] | (z['nz'][2 * i + 1] << 4) for i in range(4)]
    o.append(' {0x%08xu,%d,%d,0,0,{%s},{%s},{%s}},' % (z['hash'], z['block'], z['rho'], ','.join(map(str, z['gain'])), ','.join(map(str, z['tid'])), ','.join(map(str, nzp))))
o.append('};')
open(a.out, 'w').write('\n'.join(o) + '\n')
if a.sndidx:
    open(a.out.replace('.c', '_idx_size.txt'), 'w').write('%d\n' % (len(zones) * 36 + len(tabs_out) * 4))
print('zones %d  unique tables %d  tables %d bytes  index %d + directory %d bytes' % (len(zones), len(tabs_out), total, len(zones) * 36, len(tabs_out) * 4))
