#!/usr/bin/env python3
"""Generate gfm_tabs.h (YM2612 lookup tables) from ymfm's ymfm_fm.ipp (BSD-3, (c) Aaron Giles).

  gen_gfm_tabs.py /path/to/ymfm/src/ymfm_fm.ipp > gfm_tabs.h

The OPN tables in ymfm were extracted from the die; they are copied verbatim:
  s_sin_table[256]        4.8 log-sine (quarter wave)
  s_power_table[256]      10-bit mantissas of the exp table, stored as (m|0x400)<<2
  s_increment_table[64]   envelope increments per rate / step
  s_detune_adjustment[32][4]
"""
import re, sys
src = open(sys.argv[1]).read()

def block(name):
    m = re.search(name + r'[^=]*=\s*\{(.*?)\};', src, re.S)
    return m.group(1)

sin = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', block(r's_sin_table\[256\]'))]
pw = [(int(x, 16) | 0x400) << 2 for x in re.findall(r'X\((0x[0-9a-fA-F]+)\)', block(r's_power_table\[256\]'))]
inc = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', re.sub(r'//.*', '', block(r's_increment_table\[64\]')))]
det = [int(x) for x in re.findall(r'\b\d+\b', re.sub(r'//.*', '', block(r's_detune_adjustment\[32\]\[4\]')))]
assert len(sin) == 256 and len(pw) == 256 and len(inc) == 64 and len(det) == 128, (len(sin), len(pw), len(inc), len(det))

def arr(ctype, name, vals, fmt, per=8):
    out = [f'static const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        out.append('  ' + ','.join(fmt % v for v in vals[i:i + per]) + ',')
    out.append('};')
    return '\n'.join(out)

print('/* Generated by gen_gfm_tabs.py from ymfm (BSD-3-Clause, Copyright (c) 2021, Aaron Giles). Do not edit. */')
print(arr('uint16_t', 'gfm_sin_att', sin, '0x%03x'))
print(arr('uint16_t', 'gfm_pow', pw, '0x%04x'))
print(arr('uint32_t', 'gfm_inc', inc, '0x%08x', 4))
print(arr('uint8_t', 'gfm_detune', det, '%2d', 16))
