#!/usr/bin/env python3
"""Extracts, from the verified C core's main opcode table (z80f_ops.inc), the cases the pure-loop probe (idle_probe.c) may execute:
everything except HALT, OUT, DI/EI, the prefix bytes and a few rarely needed ones (see EXCL).  Writes core/z80_idle_cases.inc (macro Z80_IDLE_CASES).  Run from psc8/."""
import re, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'z80f_ops.inc')).read().split('\n')
out = []; on = False
EXCL = {0x76, 0xD3, 0xF3, 0xFB, 0xCB, 0xED, 0xDD, 0xFD}
# also left to the interpreter proper: ADC/SBC, DAA, 16-bit adds, (HL) read-modify-write and EX (SP),HL - no poll loop needs them and each one costs code size
EXCL |= set(range(0x88, 0xA0)) | {0xCE, 0xDE, 0x27, 0x34, 0x35, 0x09, 0x19, 0x29, 0x39, 0xE3}
for ln in src:
    if ln.startswith('#define Z80F_MAIN_CASES'): on = True; continue
    if on and ln.startswith('#define'): break
    if on:
        m = re.match(r'case 0x([0-9A-F]{2}):', ln)
        if m and int(m.group(1), 16) not in EXCL: out.append(ln.rstrip())
open(os.path.join(here, 'z80_idle_cases.inc'), 'w').write('/* generated by gen_idle_ops.py - do not edit */\n#define Z80_IDLE_CASES \\\n' + '\n'.join(out).rstrip(' \\') + '\n')
print(len(out), 'cases')
